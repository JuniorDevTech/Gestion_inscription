import mongoose from "mongoose";

const userSchema = new mongoose.Schema(
  {
    /* ================================================= */
    /* ================= FIRST NAME ==================== */
    /* ================================================= */

    firstName: {
      type: String,

      required: true,

      trim: true,
    },

    /* ================================================= */
    /* ================= LAST NAME ===================== */
    /* ================================================= */

    lastName: {
      type: String,

      required: true,

      trim: true,
    },

    /* ================================================= */
    /* ================= EMAIL ========================= */
    /* ================================================= */

    email: {
      type: String,

      required: true,

      unique: true,

      lowercase: true,

      trim: true,
    },

    /* ================================================= */
    /* ================= PASSWORD ====================== */
    /* ================================================= */

    password: {
      type: String,

      required: true,

      minlength: 6,
    },

    /* ================================================= */
    /* ================= ROLE ========================== */
    /* ================================================= */

    role: {
      type: String,

      enum: ["user", "admin"],

      default: "user",
    },

    /* ================================================= */
    /* ================= EMAIL OTP ===================== */
    /* ================================================= */

    emailOTP: {
      type: String,
    },

    emailOTPExpires: {
      type: Date,
    },

    isEmailVerified: {
      type: Boolean,

      default: false,
    },

    /* ================================================= */
    /* ================= ACCOUNT STATUS ================ */
    /* ================================================= */

    isActive: {
      type: Boolean,

      default: true,
    },

    /* ================================================= */
    /* ================= PROFILE IMAGE ================= */
    /* ================================================= */

    avatar: {
      type: String,

      default: "",
    },
  },

  {
    timestamps: true,
  },
);

/* ================================================= */
/* ================= EXPORT ========================= */
/* ================================================= */

const User = mongoose.model("User", userSchema);

export default User;
