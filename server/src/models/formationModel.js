import mongoose from "mongoose";

const formationSchema = new mongoose.Schema(
  {
    /* ================================================= */
    /* ================= TITLE ========================= */
    /* ================================================= */

    title: {
      type: String,

      required: true,

      trim: true,
    },

    /* ================================================= */
    /* ================= DESCRIPTION =================== */
    /* ================================================= */

    description: {
      type: String,

      required: true,
    },

    /* ================================================= */
    /* ================= PRICE ========================= */
    /* ================================================= */

    price: {
      type: Number,

      required: true,
    },

    /* ================================================= */
    /* ================= DURATION ====================== */
    /* ================================================= */

    duration: {
      type: String,

      required: true,
    },

    /* ================================================= */
    /* ================= LEVEL ========================= */
    /* ================================================= */

    level: {
      type: String,

      enum: ["Débutant", "Intermédiaire", "Avancé"],

      default: "Débutant",
    },

    /* ================================================= */
    /* ================= CATEGORY ====================== */
    /* ================================================= */

    category: {
      type: String,

      required: true,
    },

    /* ================================================= */
    /* ================= IMAGE ========================= */
    /* ================================================= */

    image: {
      type: String,

      default: "",
    },

    /* ================================================= */
    /* ================= STATUS ======================== */
    /* ================================================= */

    status: {
      type: String,

      enum: ["active", "inactive"],

      default: "active",
    },
  },

  {
    timestamps: true,
  },
);

const Formation = mongoose.model("Formation", formationSchema);

export default Formation;
